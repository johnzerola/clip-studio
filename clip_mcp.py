"""Clip Studio job control over MCP stdio."""
from typing import Literal
from mcp.server.fastmcp import FastMCP
from pydantic import BaseModel, Field

from job_registry import cancel, get, list_jobs, outputs, submit

server = FastMCP("clip-studio")


@server.tool()
def modelar_reference(project: str, preset: str) -> dict:
    """Verifica um preset aprovado do AI Video Director para revisão no Modelar. Não renderiza."""
    from modelar_bridge import load_profile
    return load_profile(project, preset)


class JobRequest(BaseModel):
    sources: list[str] = Field(min_length=1, max_length=8)
    output: str | None = None
    mode: Literal["render", "plan"] = "render"
    style: Literal["dynamic", "split", "reaction", "gamecam", "all"] = "dynamic"
    performance: Literal["leve", "equilibrado"] = "leve"
    acceleration: Literal["auto", "cpu"] = "auto"
    precompress: bool = True
    seconds: int = Field(45, ge=10, le=180)
    count: int = Field(1, ge=1, le=8)
    minutes: int = Field(5, ge=0, le=720)
    ranges: str = ""
    captions: bool = True
    speech_language: Literal["auto", "pt", "en", "es"] = "auto"
    capture_height: Literal[480, 720, 1080] | None = None
    replay_after_live: bool = False
    replay_height: Literal[1080, 1440] = 1440
    channel_handle: str = Field("", max_length=31)
    hook_text: str = Field("", max_length=64)
    effects_model: str = ""
    smart_reframe: bool = False
    music: bool = True
    model: str = ""
    vision_model: str = ""
    trim_inactive: bool = True
    transcribe_recordings: bool = False
    live_poll_hours: int = Field(1, ge=0, le=3)
    review: bool = False
    threshold: int = Field(60, ge=20, le=95)
    catchup: bool = False


class JobEvent(BaseModel):
    seq: int
    line: str


class JobSummary(BaseModel):
    id: str
    origin: str
    state: str
    output: str
    session: str | None = None
    created: float
    updated: float
    cancel: bool
    detail: str | None = None


class JobResult(JobSummary):
    sources: list[str]
    events: list[JobEvent] = Field(default_factory=list)


class JobList(BaseModel):
    jobs: list[JobSummary]


class JobOutputs(BaseModel):
    id: str
    session: str | None
    clips: list[str]
    plans: list[str]
    transcripts: list[str] = Field(default_factory=list)


@server.tool()
def start_job(request: JobRequest) -> JobResult:
    """Start a local file, public VOD or live clipping job that also appears in the Windows panel."""
    return JobResult(**submit(request.model_dump(), "MCP"))


@server.tool()
def job_status(job_id: str, after: int = 0) -> JobResult:
    """Read job state, session folder and up to 100 events after the supplied event cursor."""
    return JobResult(**get(job_id, after=after, limit=100))


@server.tool()
def jobs(limit: int = 25) -> JobList:
    """List recent jobs started from the panel, CLI or MCP."""
    return JobList(jobs=[JobSummary(**row) for row in list_jobs(limit)])


@server.tool()
def cancel_job(job_id: str) -> JobResult:
    """Ask a pending job to stop or stop capturing new live blocks while current work finishes."""
    return JobResult(**cancel(job_id))


@server.tool()
def job_outputs(job_id: str) -> JobOutputs:
    """Find clips and machine-readable edit plans generated by a job."""
    return JobOutputs(**outputs(job_id))


if __name__ == "__main__":
    server.run(transport="stdio")
